import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID, scryptSync } from 'node:crypto';
import { once } from 'node:events';
import { createServer, type AddressInfo } from 'node:net';
import { Pool } from 'pg';
import { chromium } from 'playwright';
import { TOTP, Secret } from 'otpauth';
import { createAdminServer } from '../apps/admin-auth.js';

test('local notification UI: browser, session boundaries, CSRF, concurrency and audit', {timeout: 90000}, async () => {
  assert.ok(process.env.TEST_DATABASE_URL);
  const admin = new Pool({connectionString:process.env.TEST_DATABASE_URL});
  const schema = `ui_${randomUUID().replaceAll('-','')}`;
  await admin.query(`CREATE SCHEMA ${schema}`);
  const db = new Pool({connectionString:process.env.TEST_DATABASE_URL, options:`-c search_path=${schema}`});
  await db.query((await readFile('infra/017_notification_settings.sql','utf8')).replace(/^\uFEFF/,''));
  await db.query('CREATE TABLE admin_totp_replay (factor_id text PRIMARY KEY, last_counter bigint NOT NULL)');
  await db.query('CREATE TABLE admin_totp_codes (factor_id text NOT NULL, digest text NOT NULL, valid_until bigint NOT NULL, PRIMARY KEY (factor_id,digest))');
  let clock=1000000000;
  const secret='AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA', salt='0123456789abcdef0123456789abcdef';
  const record=`scrypt$${salt}$${scryptSync('test password',Buffer.from(salt,'hex'),64).toString('hex')}`;
  const totp=new TOTP({secret:Secret.fromBase32(secret)});
  const code=()=>totp.generate({timestamp:clock});
  const server=createAdminServer(record,secret,db,()=>clock).listen(0,'127.0.0.1'); await once(server,'listening');
  let connections=0; const trap=createServer(socket=>{connections++;socket.destroy();}).listen(0,'127.0.0.1'); await once(trap,'listening');
  const base=`http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext(); const page=await context.newPage();
  try {
    await page.goto(base+'/admin/ui/');
    await page.getByLabel('Senha administrativa').fill('test password');
    await page.getByLabel('Código TOTP').fill(code());
    await page.getByRole('button',{name:'Entrar'}).click();
    await page.getByText('Configuração incompleta').waitFor();
    const cookie=(await context.cookies()).find(c=>c.name==='admin_session');
    assert.ok(cookie?.httpOnly); assert.equal(cookie.sameSite,'Strict'); assert.equal(cookie.path,'/admin/ui/');
    const headers={origin:base,'sec-fetch-site':'same-origin','content-type':'application/json'};
    const bootstrap=await fetch(base+'/admin/ui/bootstrap',{headers:{'sec-fetch-site':'same-origin',cookie:`admin_session=${cookie.value}`}});
    const {csrf}=await bootstrap.json() as {csrf:string};
    const post=(path:string, body:unknown, extra:Record<string,string>={})=>fetch(base+'/admin/ui/'+path,{method:'POST',headers:{...headers,cookie:`admin_session=${cookie.value}`,'x-csrf-token':csrf,...extra},body:JSON.stringify(body)});
    assert.equal((await post('preference',{enabled:false},{origin:'http://evil.test'})).status,403);
    assert.equal((await post('preference',{enabled:false},{'sec-fetch-site':'cross-site'})).status,403);
    assert.equal((await post('preference',{enabled:false},{'x-csrf-token':'bad'})).status,403);
    assert.equal((await post('preference',{enabled:false},{host:'localhost:1234'})).status,403);
    assert.equal((await fetch(base+'/admin/session',{headers:{cookie:`admin_session=${cookie.value}`}})).status,401);
    assert.equal((await fetch(base+'/admin/session',{headers:{origin:base}})).status,403);
    assert.equal((await fetch(base+'/admin/ui/login',{method:'POST',headers,body:JSON.stringify({password:'test password',code:code()})})).status,403);
    const port=(trap.address() as AddressInfo).port;
    await page.getByLabel('Provedor').selectOption('smtp');
    await page.getByLabel('Host').fill('127.0.0.1');
    await page.getByLabel('Porta').fill(String(port));
    await page.getByLabel('TLS').selectOption('starttls');
    await page.getByLabel('Remetente').fill('sender@example.test');
    await page.getByLabel('Destinatário').fill('owner@example.test');
    await page.getByRole('button',{name:'Salvar configurações'}).click();
    await page.getByText('Configurada / desativada').waitFor();
    await page.getByRole('button',{name:'Solicitar habilitação'}).click();
    await page.getByText('Habilitação solicitada — envio não operacional').waitFor();
    await page.getByLabel('Destinatário').fill('new@example.test');
    await page.getByRole('button',{name:'Salvar configurações'}).click();
    await page.getByText('Configurada / desativada').waitFor();
    const current=await (await fetch(base+'/admin/ui/settings',{headers:{'sec-fetch-site':'same-origin',cookie:`admin_session=${cookie.value}`}})).json() as Record<string,unknown>;
    const body={version:current.version,provider:'smtp',host:'127.0.0.1',port,tls_mode:'starttls',sender:'sender@example.test',recipient:'race@example.test'};
    const race=await Promise.all([post('settings',body),post('settings',{...body,recipient:'other@example.test'})]);
    assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
    assert.equal((await post('settings',{...body,password:'secret'})).status,400);
    const audit=await db.query('SELECT version,action,changed_fields FROM notification_settings_audit ORDER BY version');
    assert.deepEqual(audit.rows.map(r=>r.action),['save','enable','save','save']);
    assert.ok(audit.rows[2].changed_fields.includes('preference_requested'));
    assert.equal(JSON.stringify(audit.rows).includes('example.test'),false);
    assert.equal(connections,0);
    clock+=60000;
    const bearer=await fetch(base+'/admin/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'test password',code:code()})});
    assert.equal(bearer.status,200); const bearerToken=(await bearer.json() as {token:string}).token;
    assert.equal((await fetch(base+'/admin/ui/settings',{headers:{'sec-fetch-site':'same-origin',cookie:`admin_session=${cookie.value}`}})).status,401);
    clock+=60000;
    await page.reload();
    await page.getByLabel('Senha administrativa').fill('test password'); await page.getByLabel('Código TOTP').fill(code()); await page.getByRole('button',{name:'Entrar'}).click();
    await page.getByText('Configurada / desativada').waitFor();
    assert.equal((await fetch(base+'/admin/session',{headers:{authorization:`Bearer ${bearerToken}`}})).status,401);
    await page.getByRole('button',{name:'Sair'}).click(); await page.getByRole('button',{name:'Entrar'}).waitFor();
    clock+=60000;
    await page.getByLabel('Senha administrativa').fill('test password'); await page.getByLabel('Código TOTP').fill(code()); await page.getByRole('button',{name:'Entrar'}).click();
    await page.getByText('Configurada / desativada').waitFor();
    clock+=900000;
    await page.getByRole('button',{name:'Recarregar configuração'}).click();
    await page.getByText('Sessão inválida ou expirada. Recarregue a página.').waitFor();
  } finally {
    await browser.close(); server.close(); await once(server,'close'); trap.close(); await once(trap,'close'); await db.end(); await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.end();
  }
});
